"""Cross-section functionalization: parameter reduction of few-group tables.

Few-group constants are generated by the lattice code over a space of state
variables (fuel / graphite temperature, salt density, fissile and fission-
product content).  The table (n_states x n_constants) is compressed with PCA
and the principal-component scores are regressed on the state variables,
replacing the multi-dimensional table by a handful of smooth functions.
"""
from __future__ import annotations

import numpy as np

from ..lattice import CellGeometry, fundamental_mode, run_lattice
from ..macro import condense
from ..materials import graphite, salt_at_temperature
from ..xs.energy import few_group
from .design_space import DesignSpace, Parameter
from .surrogate import make_surrogate

STATE_SPACE = DesignSpace([
    Parameter("T_fuel", 800.0, 1100.0, 900.0, unit="K", label="Fuel temperature [K]"),
    Parameter("T_graphite", 800.0, 1100.0, 920.0, unit="K", label="Graphite temperature [K]"),
    Parameter("fissile_factor", 0.7, 1.3, 1.0, label="Fissile density factor"),
    Parameter("fp_poison", 0.0, 1.0, 0.0, label="Lumped FP poison level"),
])

XS_NAMES_2G = ["D1", "D2", "Sa1", "Sa2", "nSf1", "nSf2", "kSf1", "kSf2", "S12", "S21"]


def xs_vector(design, state: dict, groups: str = "2g") -> np.ndarray:
    z = design.zones[0]
    s = salt_at_temperature(design.fuel_salt(), state["T_fuel"])
    for n in ("U233", "U235", "Pu239", "Pu241"):
        if n in s.N:
            s.N[n] *= state["fissile_factor"]
    # lumped rare-earth poison: up to ~1% of the heavy-metal atom density
    hm = sum(v for k, v in s.N.items() if k.startswith(("Th", "U", "Pu")))
    s.N["LFP_RE"] = s.N.get("LFP_RE", 0.0) + 0.01 * hm * state["fp_poison"]
    mod = graphite(design.graphite_density, state["T_graphite"])
    r = run_lattice(s, mod, CellGeometry(z.channel_radius, z.salt_fraction, z.lattice))
    B2 = (2.405 / (design.core_radius + 20.0)) ** 2 + (np.pi / (design.core_height + 40.0)) ** 2
    k, phi, D = fundamental_mode(r.hom, B2)
    c = condense(r.hom, phi, few_group(groups), D=D)
    return np.array([c.D[0], c.D[1], c.absorption[0] - c.n2n[0], c.absorption[1],
                     c.nu_fission[0], c.nu_fission[1], c.kappa_fission[0], c.kappa_fission[1],
                     c.scatter[0, 1], c.scatter[1, 0]])


def xs_table(design, X) -> np.ndarray:
    return np.array([xs_vector(design, st) for st in STATE_SPACE.as_dicts(X)])


class XSFunctionalization:
    def __init__(self, energy: float = 0.99999, kind: str = "poly", space: DesignSpace = STATE_SPACE,
                 seed: int = 0):
        self.energy, self.kind, self.space, self.seed = energy, kind, space, seed

    def fit(self, X, Y):
        Y = np.asarray(Y, float)
        self.mu, self.sd = Y.mean(0), Y.std(0)
        self.sd[self.sd == 0] = 1.0
        Z = (Y - self.mu) / self.sd
        U, s, Vt = np.linalg.svd(Z, full_matrices=False)
        cum = np.cumsum(s ** 2) / np.sum(s ** 2)
        self.cumulative_variance = cum
        self.singular_values = s
        self.rank = int(np.searchsorted(cum, self.energy) + 1)
        self.components = Vt[: self.rank]
        scores = Z @ self.components.T
        self.models = [make_surrogate(self.kind, self.space, seed=self.seed).fit(X, scores[:, j])
                       for j in range(self.rank)]
        return self

    def predict(self, X) -> np.ndarray:
        S = np.column_stack([m.predict(X) for m in self.models])
        return (S @ self.components) * self.sd + self.mu

    def relative_errors(self, X, Y) -> np.ndarray:
        P = self.predict(X)
        return np.abs(P - Y) / np.abs(Y)
